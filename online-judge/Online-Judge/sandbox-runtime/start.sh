#!/bin/sh
# 第一行指定使用容器里的命令解释器执行这个脚本。
# 这个文件是容器启动入口，负责准备资源控制和目录权限，最后启动管理程序。
# 资源控制组可以理解为“给一组进程设置共同限额的文件夹”。
# 其中的控制文件由内核提供，向文件写值就是向内核发出管理请求。
# 贯穿本文件的例子：假设 /cg 下只有 /cg/task-001 这一个子目录。

# -e 表示普通命令失败时结束脚本，避免准备失败后仍启动判题。
# -u 表示读取未设置的变量时报错，避免空路径被误用。
# 注意：条件判断中用于决定分支的失败有例外，下面会显式处理失败。
set -eu

# find 用来查找目录；/cg 是查找起点。
# -mindepth 1 排除起点本身，-maxdepth 1 只查看直接子项，-type d 只选目录。
# $(...) 先执行括号里的命令，再把输出放到当前位置。
# set -- 将查找结果设置为脚本的位置参数，后面可用 $1、$2 依次取得。
# 例子：只找到 /cg/task-001 时，$1 就是 /cg/task-001，参数数量是 1。
# 这里依赖系统生成的控制组路径不含空白字符，因为未加引号的结果会按空白拆分。
set -- $(find /cg -mindepth 1 -maxdepth 1 -type d)

# [ ... ] 是条件检查命令，括号内侧必须有空格。
# $# 表示参数数量，-eq 表示整数相等，-d 表示路径确实是目录。
# && 表示前一步成功才执行后一步，|| 表示前面的判断失败时执行后一步。
# 双引号保证路径作为一个完整参数传入；exit 70 表示以非零错误码退出。
# 例子：找到两个子目录就退出，避免管理程序选错本容器的资源范围。
[ "$#" -eq 1 ] && [ -d "$1" ] || exit 70

# 保存资源根目录。命令解释器的变量赋值要求等号两边不能有空格。
# 例子：后续 "$group/manager" 会展开成 /cg/task-001/manager。
group=$1

# mkdir 创建目录；在控制组文件系统里，这也创建了一个新的子资源组。
# 将管理程序放入单独子组，才能在父组上启用对子组的资源控制。
mkdir "$group/manager"

# $$ 是当前命令解释器的进程编号，echo 输出这个编号。
# > 把输出写入右侧文件；写入 cgroup.procs 会让内核将该进程移动到对应组。
# 例子：当前进程编号为 12，就把 12 写入 /cg/task-001/manager/cgroup.procs。
echo $$ > "$group/manager/cgroup.procs"

# 启用子组的处理器、内存、进程数量控制能力；加号表示启用。
# 这一步只是启用能力，具体限额由后面的管理程序为编译组、用例组设置。
echo '+cpu +memory +pids' > "$group/cgroup.subtree_control"

# chmod 修改访问权限，三个数字依次对应所有者、所属组、其他用户。
# 每个数字由读 4、写 2、执行 1 相加得到；目录的“执行”权限表示允许进入。
# 700 表示只有所有者可以读写和进入。用户程序降权后不能访问这些管理目录。
chmod 700 /cg /control

# 755 表示所有者可读写进入，其他用户只能读取和进入。
# 例子：普通用户能读取 /artifact 下允许读取的编译结果，却不能在该目录创建文件。
# 用例专用可写目录的权限由管理程序另外设置。
chmod 755 /work /artifact

# exec 用新程序替换当前命令解释器，进程编号保持不变，资源组归属也会保留。
# java 启动虚拟机，-Xms16m 指初始堆大小为十六兆字节，-Xmx48m 指最大堆为四十八兆字节。
# -XX:-UsePerfData 关闭虚拟机性能数据文件，减少对临时目录的依赖。
# -cp 后是查找已编译类的目录，SandboxManager 是含启动方法的管理类。
# 最后的 "$group" 是传给管理类的第一个参数。
# 例子：本例中管理程序收到 /cg/task-001，随后在其下创建编译和用例资源组。
exec java -Xms16m -Xmx48m -XX:-UsePerfData -cp /opt/sandbox/classes SandboxManager "$group"
